#!/usr/bin/env python3
"""Verify/rebuild PIE 2.1 words using Espressif binutils, never required by Cargo.
Usage: scripts/pie-opcodes.py /path/to/as-xespv2p1 /path/to/objdump-xespv2p1 [--write]
Tool version tested: crosstool-NG esp-15.2.0_20251204, binutils 2.45.
"""
import pathlib, re, subprocess, sys, tempfile
root = pathlib.Path(__file__).resolve().parent.parent
source = root / 'src/hal/pie/kernels.S'
output = root / 'src/hal/pie/encoded.S'
with tempfile.TemporaryDirectory(prefix='p4-pie-') as tmp:
    obj = pathlib.Path(tmp) / 'kernels.o'
    subprocess.run([sys.argv[1], '-march=rv32imafc_xespv2p1_xesploop', '-mno-relax', '-o', str(obj), str(source)], check=True)
    dis = subprocess.check_output([sys.argv[2], '-d', str(obj)], text=True)
    words = iter(re.findall(r'^\s*[0-9a-f]+:\s+([0-9a-f]{8})\s+esp\.', dis, re.M))
    result = ['# Generated by scripts/pie-opcodes.py from kernels.S; PIE 2.1, not 2.2.\n']
    count = 0
    for line in source.read_text().splitlines(keepends=True):
        if line.lstrip().startswith('esp.'):
            word = next(words)
            result.append('    .word 0x' + word + ' # ' + line.strip() + '\n')
            count += 1
        else:
            result.append(line)
    assert next(words, None) is None
    text = ''.join(result)
    if '--write' in sys.argv[3:]:
        output.write_text(text)
    else:
        assert output.read_text() == text, 'encoded.S differs; inspect tool/version and regenerate with --write'
    print(f'PIE 2.1: {count} instruction encodings verified')
